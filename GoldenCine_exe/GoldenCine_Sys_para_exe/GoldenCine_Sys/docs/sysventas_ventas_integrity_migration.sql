-- Apply only after reviewing/backing up the target database.
-- Aligns an already-created SysVentas_Ventas schema with the current Java model.
BEGIN;

-- Current code allows one function line per detail row. Give each line its own key.
ALTER TABLE sysventas_ventas.venta_detalle_service
    ADD COLUMN IF NOT EXISTS id_detalle_servicio BIGINT GENERATED BY DEFAULT AS IDENTITY;
UPDATE sysventas_ventas.venta_detalle_service
   SET id_detalle_servicio = DEFAULT
 WHERE id_detalle_servicio IS NULL;

DO $$
DECLARE
    pk_name TEXT;
    pk_has_new_id BOOLEAN;
BEGIN
    SELECT c.conname,
           EXISTS (
               SELECT 1 FROM unnest(c.conkey) AS key_column(attnum)
               JOIN pg_attribute a ON a.attrelid = c.conrelid AND a.attnum = key_column.attnum
               WHERE a.attname = 'id_detalle_servicio'
           )
      INTO pk_name, pk_has_new_id
      FROM pg_constraint c
     WHERE c.conrelid = 'sysventas_ventas.venta_detalle_service'::regclass
       AND c.contype = 'p';

    IF pk_name IS NOT NULL AND NOT pk_has_new_id THEN
        EXECUTE format('ALTER TABLE sysventas_ventas.venta_detalle_service DROP CONSTRAINT %I', pk_name);
        pk_name := NULL;
    END IF;
    IF pk_name IS NULL THEN
        ALTER TABLE sysventas_ventas.venta_detalle_service
            ADD CONSTRAINT pk_venta_detalle_service PRIMARY KEY (id_detalle_servicio);
    END IF;
END $$;

-- Older app builds may have inserted a function with no type. Backfill the same
-- default used by the Java app before enforcing the required value.
UPDATE sysventas_ventas.cartelera
   SET tipo_funcion = 'NOCHE'
 WHERE tipo_funcion IS NULL;

ALTER TABLE sysventas_ventas.peliculas ALTER COLUMN id_genero SET NOT NULL;
ALTER TABLE sysventas_ventas.sala ALTER COLUMN id_tipo_sala SET NOT NULL;
ALTER TABLE sysventas_ventas.producto ALTER COLUMN id_tipo SET NOT NULL;
ALTER TABLE sysventas_ventas.cartelera ALTER COLUMN tipo_funcion SET NOT NULL;

COMMIT;
