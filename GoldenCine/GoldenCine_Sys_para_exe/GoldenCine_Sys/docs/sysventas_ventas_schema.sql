-- PostgreSQL schema for SysVentas_Ventas.
-- Uses the ModeloFinal Architect entities/relations and adds fields required by the current UI.
CREATE SCHEMA IF NOT EXISTS sysventas_ventas;

CREATE TABLE IF NOT EXISTS sysventas_ventas.tipo_sala (
    id_tipo_sala BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(60) NOT NULL UNIQUE,
    estado VARCHAR(2) NOT NULL DEFAULT 'A'
);
CREATE TABLE IF NOT EXISTS sysventas_ventas.genero (
    id_genero BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(60) NOT NULL UNIQUE
);
CREATE TABLE IF NOT EXISTS sysventas_ventas.peliculas (
    id_peliculas BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(150) NOT NULL,
    id_genero BIGINT NOT NULL REFERENCES sysventas_ventas.genero(id_genero)
);
CREATE TABLE IF NOT EXISTS sysventas_ventas.sala (
    idsala BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    id_tipo_sala BIGINT NOT NULL REFERENCES sysventas_ventas.tipo_sala(id_tipo_sala),
    cantidad INTEGER NOT NULL DEFAULT 0,
    libre BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE IF NOT EXISTS sysventas_ventas.usuario (
    id_usuario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario VARCHAR(80) NOT NULL UNIQUE,
    clave VARCHAR(255) NOT NULL,
    estado VARCHAR(2) NOT NULL DEFAULT 'A'
);
CREATE TABLE IF NOT EXISTS sysventas_ventas.cliente (
    id_cliente VARCHAR(20) PRIMARY KEY,
    nombres VARCHAR(150) NOT NULL,
    rep_legal VARCHAR(150),
    tipo_documento VARCHAR(20) NOT NULL,
    edad INTEGER NOT NULL CHECK (edad BETWEEN 0 AND 120)
);
CREATE TABLE IF NOT EXISTS sysventas_ventas.cartelera (
    id_servicio BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_cartera VARCHAR(100) NOT NULL,
    pu NUMERIC(10,2) NOT NULL CHECK (pu >= 0),
    utilidad NUMERIC(10,2) NOT NULL DEFAULT 0,
    cantidad INTEGER NOT NULL DEFAULT 0,
    idpelicula BIGINT NOT NULL REFERENCES sysventas_ventas.peliculas(id_peliculas),
    idsala BIGINT NOT NULL REFERENCES sysventas_ventas.sala(idsala),
    id_usuario BIGINT REFERENCES sysventas_ventas.usuario(id_usuario),
    hora_inicio TIME,
    hora_fin TIME,
    tipo_funcion VARCHAR(30) NOT NULL
);
CREATE TABLE IF NOT EXISTS sysventas_ventas.promociones (
    idproductocine BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombremedida VARCHAR(100) NOT NULL,
    id_servicio BIGINT REFERENCES sysventas_ventas.cartelera(id_servicio)
);
CREATE TABLE IF NOT EXISTS sysventas_ventas.tipo (
    id_tipo BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(30) NOT NULL UNIQUE
);
CREATE TABLE IF NOT EXISTS sysventas_ventas.producto (
    id_producto BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    tipo VARCHAR(30) NOT NULL,
    precio NUMERIC(10,2) NOT NULL CHECK (precio >= 0),
    stockDisponible INTEGER NOT NULL CHECK (stockDisponible >= 0),
    id_tipo BIGINT NOT NULL REFERENCES sysventas_ventas.tipo(id_tipo)
);
CREATE TABLE IF NOT EXISTS sysventas_ventas.carrito_venta (
    id_carrito BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente VARCHAR(20) REFERENCES sysventas_ventas.cliente(id_cliente),
    id_usuario BIGINT REFERENCES sysventas_ventas.usuario(id_usuario),
    creado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS sysventas_ventas.venta (
    id_venta BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente VARCHAR(20) NOT NULL REFERENCES sysventas_ventas.cliente(id_cliente),
    id_usuario BIGINT NOT NULL REFERENCES sysventas_ventas.usuario(id_usuario),
    fecha_gener TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    precio_base NUMERIC(10,2) NOT NULL DEFAULT 0,
    igv NUMERIC(10,2) NOT NULL DEFAULT 0,
    precio_total NUMERIC(10,2) NOT NULL DEFAULT 0,
    serie VARCHAR(20),
    num_doc VARCHAR(30),
    tipo_doc VARCHAR(30)
);
CREATE TABLE IF NOT EXISTS sysventas_ventas.venta_detalle_service (
    id_detalle_servicio BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_venta BIGINT NOT NULL REFERENCES sysventas_ventas.venta(id_venta) ON DELETE CASCADE,
    precio NUMERIC(10,2) NOT NULL,
    cantidad INTEGER NOT NULL CHECK (cantidad > 0),
    precio_total NUMERIC(10,2) NOT NULL,
    id_servicio BIGINT NOT NULL REFERENCES sysventas_ventas.cartelera(id_servicio),
    descuento NUMERIC(10,2) NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS sysventas_ventas.venta_detalle_product (
    id_venta_det_prod BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_producto BIGINT NOT NULL REFERENCES sysventas_ventas.producto(id_producto),
    id_venta BIGINT NOT NULL REFERENCES sysventas_ventas.venta(id_venta) ON DELETE CASCADE,
    cantidad INTEGER NOT NULL CHECK (cantidad > 0),
    precio NUMERIC(10,2) NOT NULL,
    subtotal NUMERIC(10,2) NOT NULL
);

